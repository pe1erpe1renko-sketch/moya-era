-- Очередь 3: AI-образы — карточки со своим арканом
-- ═══════════════════════════════════════════════════════════════════
--
-- У каждой карточки свой постоянный адрес /obraz/<код>. Страница
-- индексируется и разворачивается превьюшкой при пересылке — ради этого
-- всё и затевалось: образ единственный бесплатный канал привлечения.
--
-- КОД СЛУЧАЙНЫЙ, а не выведенный из даты рождения. Из адреса не должно
-- восстанавливаться ничего о человеке: адресами делятся в открытую, и
-- подобрать чужой перебором тоже не должно получаться.
--
-- ЗДЕСЬ ЛЕЖИТ ТОЛЬКО ТО, ЧТО ЧЕЛОВЕК РАЗРЕШИЛ ПОКАЗАТЬ. Снял галочку с
-- имени — имя не сохраняется вовсе, а не прячется при выводе. Так на
-- странице физически нечего показать лишнего, даже по ошибке.

CREATE TABLE IF NOT EXISTS public.images (
  code        text PRIMARY KEY,                                  -- код в адресе
  theme       text NOT NULL,                                     -- 'core', 'day', 'money' …
  label       text NOT NULL,                                     -- подпись темы: «Деньги»
  arcana      smallint NOT NULL CHECK (arcana BETWEEN 1 AND 22),
  title       text,                                              -- «Перерождение», если показано
  line        text,                                              -- строка смысла, если показана
  name        text,                                              -- имя, если показано
  birth_date  date,                                              -- дата, если показана
  user_id     uuid REFERENCES auth.users(id) ON DELETE SET NULL, -- null у незарегистрированных
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS images_user_created ON public.images (user_id, created_at DESC);

ALTER TABLE public.images ENABLE ROW LEVEL SECURITY;

-- ЧИТАТЬ ИЗ БРАУЗЕРА НЕЛЬЗЯ НИКОМУ, даже по коду.
--
-- Страница образа собирается на сервере сервисным ключом, и это не
-- лишняя строгость: политика «читать всем» позволила бы с анонимным
-- ключом выгрузить таблицу целиком — то есть все имена и все даты
-- рождения разом. Случайный код защищает одну карточку, но не от
-- выборки без условия.
--
-- Своё видно владельцу — на будущий список «мои образы» в кабинете.
DROP POLICY IF EXISTS images_select_own ON public.images;
CREATE POLICY images_select_own ON public.images
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

-- Запись — только сервисным ключом с сервера: там проверяется доступ.
