/** Свёртка: пока число больше 22 — складываем его цифры. */
export function reduceTo22(value: number): number {
  let n = value;
  while (n > 22) {
    n = String(n)
      .split("")
      .reduce((sum, d) => sum + Number(d), 0);
  }
  return n;
}

export function digitSum(value: number): number {
  return String(value)
    .split("")
    .reduce((sum, d) => sum + Number(d), 0);
}

/** Центральный аркан матрицы судьбы: число от 1 до 22. */
export function centralArcanum(day: number, month: number, year: number): number {
  const a = reduceTo22(day);
  const b = month;
  const c = reduceTo22(digitSum(year));
  const d = reduceTo22(a + b + c);
  return reduceTo22(a + b + c + d);
}

export function isValidDate(day: number, month: number, year: number): boolean {
  const date = new Date(year, month - 1, day);
  return (
    date.getFullYear() === year && date.getMonth() === month - 1 && date.getDate() === day
  );
}

/**
 * Дата рождения ещё не наступила.
 *
 * Списки годов в калькуляторах кончаются текущим годом, но день и месяц
 * внутри него можно выбрать любые — и 31 декабря проходило как дата
 * рождения. Одна проверка на все три калькулятора, чтобы они не
 * расходились в том, что считать будущим.
 */
export function isFutureDate(day: number, month: number, year: number, now: Date = new Date()): boolean {
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();
  return new Date(year, month - 1, day).getTime() > today;
}
