/**
 * ДЕТЕРМИНИРОВАННАЯ СЛУЧАЙНОСТЬ ДЛЯ ВЁРСТКИ.
 *
 * Звёзды на карточках направлений рисуются в разметке, и разметка
 * собирается дважды: на сервере и в браузере. С `Math.random` два
 * прогона дают разные координаты, React замечает расхождение при
 * гидратации и оставляет серверные — с предупреждением в консоли на
 * каждой странице, где есть такие карточки.
 *
 * Генератор с зерном даёт одинаковую последовательность там и там.
 * Это не криптография и не должна ею быть: для кодов и раздачи карт —
 * `crypto`, для звёздочек — вот это.
 *
 * mulberry32: 32-битное состояние, период 2³², равномерное [0, 1).
 */
export function seededRandom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Зерно из строки — чтобы у каждой карточки был свой, но постоянный рисунок. */
export function seedFrom(text: string): number {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
