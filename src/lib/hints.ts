/** Система, в которой человек сейчас читает разбор. */
export type HintPlace = "matrix" | "pair" | "natal" | "humandesign" | "numerology" | "tarot";

export type HintContext = {
  place: HintPlace;
  /** дата рождения разбора, YYYY-MM-DD; у пары — первая из двух */
  iso: string | null;
};

export type Hint = {
  /** устойчивый идентификатор: по нему запоминается, что подсказку уже видели */
  id: string;
  text: string;
  /**
   * Куда ведёт ссылка. `href` возвращает null, когда вести некуда, —
   * например, адрес собирается из даты, а даты у разбора нет. Такая
   * подсказка не показывается вовсе: кнопка в никуда хуже её отсутствия.
   */
  action?: { label: string; href: (ctx: HintContext) => string | null };
  /** где показывать; пусто — везде */
  where?: HintPlace[];
};

const url = (iso: string | null) => {
  if (!iso) return null;
  const [y, m, d] = iso.split("-");
  return `${d}-${m}-${y}`;
};

