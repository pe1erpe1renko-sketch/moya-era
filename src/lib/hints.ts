/**
 * ДЛИНА ТЕКСТА. Карточка шириной с телефон: заголовок в одну строку,
 * текст в две. Длиннее — и карточка перестаёт быть подсказкой.
 */

/** Подсказки, которые уместны здесь и которых человек ещё не видел. */
export function pickHints(ctx: HintContext, seen: string[]): Hint[] {
  return HINTS.filter((h) => {
    if (seen.includes(h.id)) return false;
    if (h.where && !h.where.includes(ctx.place)) return false;
    if (h.action && h.action.href(ctx) === null) return false;
    return true;
  });
}

