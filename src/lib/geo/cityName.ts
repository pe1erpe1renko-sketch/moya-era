/**
 * НАЗВАНИЕ ГОРОДА В РОДИТЕЛЬНОМ ПАДЕЖЕ — для подписи «(по времени Новосибирска)».
 *
 * В справочнике почти девятнадцать тысяч мест, и просклонять их все по
 * правилам нельзя: у части названий беглая гласная (Череповец → Череповца,
 * Орёл → Орла, Торжок → Торжка), у части род не выводится из окончания
 * (Тверь женского рода, Анадырь мужского), а составные названия требуют
 * согласования (Нижний Новгород → Нижнего Новгорода, Ростов-на-Дону →
 * Ростова-на-Дону).
 *
 * Поэтому здесь работает простое правило: склоняем только то, в чём
 * уверены, а во всех остальных случаях возвращаем null. Подпись тогда
 * строится безопасно — «(по времени города Ростов-на-Дону)». Чуть более
 * казённо, зато без ошибок в падеже на странице, которую читают тысячи
 * человек.
 */

/** После этих согласных в родительном падеже пишется «и», а не «ы»: Калуга → Калуги. */
const HUSHING = new Set(["г", "к", "х", "ж", "ч", "ш", "щ"]);

/** Окончания, которые не склоняются: Сочи, Иваново, Баку, Улан-Удэ, Грозный. */
const INDECLINABLE_END = new Set(["о", "е", "ё", "и", "у", "ы", "э", "ю", "й"]);

/**
 * Окончания-ловушки, где родительный падеж не выводится из правила:
 * беглая гласная (Череповец, Торжок, Орёл) и неопределимый род (Тверь
 * женского рода, но Анадырь мужского).
 */
const RISKY_END = ["ец", "ок", "ёк", "ёл", "рь"];

/** Предлог внутри названия: «Ростов-на-Дону» склоняется первым словом, а не последним. */
const PREPOSITIONS = new Set(["на", "в", "во", "под", "при", "у", "за", "над"]);

const CYRILLIC = /^[а-яё]+$/i;

/** Одно слово в родительном падеже. null — форма не очевидна. */
function wordGenitive(word: string): string | null {
  if (!CYRILLIC.test(word)) return null;
  const lower = word.toLowerCase();
  if (lower.length < 3) return null;
  if (RISKY_END.some((end) => lower.endsWith(end))) return null;

  const last = lower[lower.length - 1];
  const stem = word.slice(0, -1);

  if (last === "а") return stem + (HUSHING.has(lower[lower.length - 2]) ? "и" : "ы");
  if (last === "я") return stem + "и";
  // Города на «-ль» мужского рода (Ярославль, Ставрополь, Суздаль),
  // остальные на мягкий знак — женского (Пермь, Казань, Обь, Керчь).
  if (last === "ь") return stem + (lower.endsWith("ль") ? "я" : "и");
  if (INDECLINABLE_END.has(last)) return null;
  return word + "а";
}

/**
 * «Новосибирск» → «Новосибирска», «Москва» → «Москвы».
 * null, если правило не срабатывает наверняка.
 */
export function cityGenitive(name: string): string | null {
  const clean = name.trim();
  // Составное название требует согласования: «Нижнего Новгорода».
  if (!clean || /\s/.test(clean)) return null;

  const parts = clean.split("-");
  // «Ростов-на-Дону»: склоняется первое слово, а не последнее.
  if (parts.some((p) => PREPOSITIONS.has(p.toLowerCase()))) return null;

  const tail = wordGenitive(parts[parts.length - 1]);
  return tail === null ? null : [...parts.slice(0, -1), tail].join("-");
}
