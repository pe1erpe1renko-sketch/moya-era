/**
 * ВОРОТА И ЛИНИИ ДИЗАЙНА ЧЕЛОВЕКА
 *
 * Шестьдесят четыре ворот разложены по кругу зодиака в порядке, который
 * задан самой системой (он не совпадает с порядком гексаграмм в Книге
 * перемен). Отсчёт начинается с ворот 41 в 2°00′ Водолея, то есть на 302°
 * эклиптической долготы. Каждые ворота занимают 360/64 = 5,625°, внутри
 * ворот шесть линий по 0,9375°.
 *
 * Порядок ворот и точка отсчёта сверены с открытым калькулятором
 * human-design-mcp (MIT, ссылается на Jovian Archive): там колесо задано
 * от других ворот и другого градуса, но после поворота совпадает с нашим
 * до последнего элемента.
 */

import { norm360 } from "@/lib/ephemeris";

/** Ворота по кругу, начиная с 41 на 302°. */
export const GATE_WHEEL: number[] = [
  41, 19, 13, 49, 30, 55, 37, 63, 22, 36, 25, 17, 21, 51, 42, 3,
  27, 24, 2, 23, 8, 20, 16, 35, 45, 12, 15, 52, 39, 53, 62, 56,
  31, 33, 7, 4, 29, 59, 40, 64, 47, 6, 46, 18, 48, 57, 32, 50,
  28, 44, 1, 43, 14, 34, 9, 5, 26, 11, 10, 58, 38, 54, 61, 60,
];

/** Долгота начала первых ворот круга (ворота 41), градусы. */
export const WHEEL_START = 302;

export const GATE_SIZE = 360 / 64; // 5.625°
export const LINE_SIZE = GATE_SIZE / 6; // 0.9375°

export type GateLine = {
  gate: number;
  /** 1…6 */
  line: number;
  /** 1…6 — цвет, следующий уровень дробления */
  color: number;
  /** 1…6 — тон */
  tone: number;
  /** 1…5 — база */
  base: number;
  /** сколько градусов пройдено внутри ворот */
  offset: number;
};

/** Ворота, линия и более мелкие деления по эклиптической долготе. */
export function gateAt(longitude: number): GateLine {
  const shifted = norm360(longitude - WHEEL_START);
  const index = Math.floor(shifted / GATE_SIZE) % 64;
  const offset = shifted - index * GATE_SIZE;

  const linePos = offset / LINE_SIZE;
  const line = Math.min(6, Math.floor(linePos) + 1);
  const inLine = linePos - Math.floor(linePos);

  const colorPos = inLine * 6;
  const color = Math.min(6, Math.floor(colorPos) + 1);
  const inColor = colorPos - Math.floor(colorPos);

  const tonePos = inColor * 6;
  const tone = Math.min(6, Math.floor(tonePos) + 1);
  const inTone = tonePos - Math.floor(tonePos);

  const base = Math.min(5, Math.floor(inTone * 5) + 1);

  return { gate: GATE_WHEEL[index], line, color, tone, base, offset };
}

/** Долгота начала ворот, градусы. */
export function gateStart(gate: number): number {
  const index = GATE_WHEEL.indexOf(gate);
  if (index < 0) throw new Error(`Нет таких ворот: ${gate}`);
  return norm360(WHEEL_START + index * GATE_SIZE);
}

