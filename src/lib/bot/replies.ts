/**
 * ПРИГЛАШЕНИЕ НА САЙТ — не чаще раза в десять сообщений.
 *
 * Оно для тех, кто пришёл только в бота и на сайте не был. Каждое утро
 * звать одного и того же человека — это уже не помощь, а реклама.
 */
export const INVITE_EVERY = 10;

export function showsInvite(sentCount: number): boolean {
  return sentCount > 0 && sentCount % INVITE_EVERY === 0;
}

