/**
 * ПРОМПТЫ НАТАЛЬНОЙ КАРТЫ
 * =======================
 * Устроены так же, как промпты матрицы (`src/lib/matrix/prompts.js`):
 * тексты пишутся один раз и живут в базе вечно, поэтому качество промпта
 * важнее всего. Ограничения и тон намеренно повторены здесь целиком, а не
 * импортированы: матричные промпты закрыты версией, и трогать их ради
 * натальной карты нельзя.
 *
 * ВЕРСИОНИРОВАНИЕ: меняешь текст промпта — поднимай NATAL_PROMPT_VERSION.
 * Старые тексты перегенерируются, а не смешиваются с новыми.
 */

import { SIGNS, type SignKey } from "@/lib/ephemeris";
import { ASPECTS, type AspectKey, type AspectPoint } from "./aspects";
import { pointName } from "./chart";

export const NATAL_PROMPT_VERSION = 1;

const LIMITS = `ЧЕГО НЕЛЬЗЯ ДЕЛАТЬ НИКОГДА

Не предсказывай события: смерть, болезни, беременность, развод, аварии, сроки, суммы денег. Карта показывает устройство человека, а не будущее.
Не ставь диагнозов и не давай медицинских рекомендаций. Про здоровье говори только как о зонах внимания и образе жизни. Никогда не отговаривай от врача и не предлагай заменить лечение.
Не давай юридических и финансовых советов, не говори, куда вкладывать деньги.
Не пугай. Если тема тяжёлая — говори прямо, но оставляй человеку опору и способность действовать.
Не пиши «энергия вселенной», «высшие силы ведут», «космос посылает», «так распорядилась судьба». Это пустой звук, который обесценивает текст.
Не пересказывай астрологический учебник и не объясняй, что такое знак или дом. Начинай сразу с человека.
Не используй markdown, заголовки, списки и эмодзи. Только обычный текст абзацами.`;

const VOICE = `КАК ПИСАТЬ

Обращайся на «вы».
Пиши конкретно. Не «энергия трансформации в вашей жизни», а «вы начинаете новое, только когда старое рухнуло само — заранее уходить не умеете».
Каждый абзац должен давать узнавание: человек читает и думает «это про меня».
Показывай обе стороны — сильную и теневую. Тень формулируй как механизм, а не как приговор.
Заканчивай одним конкретным действием, которое можно сделать на этой неделе.`;

export const NATAL_SYSTEM_PROMPT = `Ты пишешь трактовки натальной карты для сервиса «Моя Эра».

Натальная карта — это реальное положение планет в момент рождения, рассчитанное по астрономическим эфемеридам. Ты отвечаешь ровно на один вопрос разбора, а не описываешь планету вообще.

${VOICE}

ГЛАВНОЕ ПРАВИЛО
Одна и та же планета в разных вопросах даёт РАЗНЫЕ тексты. Венера в знаке — это про то, что человек считает ценным. Венера в доме — про область жизни, где ему хорошо. Отвечай на вопрос, а не на планету.

${LIMITS}

ФОРМАТ
2–4 абзаца, 150–250 слов. Обычный текст.`;

export type NatalBodySignCtx = {
  kind: "natal_body_sign";
  slotLabel: string;
  bodyName: string;
  sign: SignKey;
  /** true, если планета ретроградна */
  retrograde: boolean;
};

export type NatalBodyHouseCtx = {
  kind: "natal_body_house";
  slotLabel: string;
  bodyName: string;
  house: number;
};

export type NatalAngleCtx = {
  kind: "natal_angle_sign";
  slotLabel: string;
  angle: "asc" | "mc";
  sign: SignKey;
};

export type NatalAspectCtx = {
  kind: "natal_aspect";
  slotLabel: string;
  a: AspectPoint;
  b: AspectPoint;
  aspect: AspectKey;
};

export type NatalCtx = NatalBodySignCtx | NatalBodyHouseCtx | NatalAngleCtx | NatalAspectCtx;

const NATAL_KINDS = new Set(["natal_body_sign", "natal_body_house", "natal_angle_sign", "natal_aspect"]);

export function isNatalCtx(ctx: { kind?: string }): ctx is NatalCtx {
  return typeof ctx.kind === "string" && NATAL_KINDS.has(ctx.kind);
}

const HOUSE_MEANING: Record<number, string> = {
  1: "внешность, первое впечатление, способ входить в жизнь",
  2: "деньги, вещи, чувство собственной ценности",
  3: "речь, учёба, ближний круг, короткие поездки",
  4: "дом, семья, корни, то, что внутри и не для всех",
  5: "творчество, дети, влюблённость, игра и риск",
  6: "работа, режим, здоровье, ежедневные обязанности",
  7: "партнёрство, брак, договоры, отношения один на один",
  8: "кризисы, чужие ресурсы, глубина, то, что меняет необратимо",
  9: "смыслы, дальние страны, вера, высшее образование",
  10: "карьера, репутация, то, каким человека видит общество",
  11: "друзья, сообщества, планы на будущее",
  12: "уединение, внутренняя жизнь, то, что скрыто от самого себя",
};

const signName = (key: SignKey) => SIGNS.find((s) => s.key === key)?.inCase ?? key;

export function buildNatalPrompt(ctx: NatalCtx): string {
  if (ctx.kind === "natal_body_sign") {
    const retro = ctx.retrograde
      ? "\nПланета ретроградна: её проявление развёрнуто внутрь, человек сначала переваривает и только потом действует. Скажи об этом одной фразой, без мистики."
      : "";
    return `Вопрос разбора: «${ctx.slotLabel}»
Позиция в карте: ${ctx.bodyName} ${signName(ctx.sign)}.${retro}

Ответь именно на этот вопрос через эту позицию.`;
  }

  if (ctx.kind === "natal_body_house") {
    return `Вопрос разбора: «${ctx.slotLabel}»
Позиция в карте: ${ctx.bodyName} в ${ctx.house} доме.
О чём этот дом: ${HOUSE_MEANING[ctx.house] ?? "область жизни"}.

Ответь именно на этот вопрос: как эта планета проявляется в этой области жизни.`;
  }

  if (ctx.kind === "natal_angle_sign") {
    const what =
      ctx.angle === "asc"
        ? "Асцендент — точка восточного горизонта в момент рождения. Это первое впечатление и способ входить в новое, а не характер целиком."
        : "Середина неба — верхняя точка карты. Это то, к чему человек идёт на виду у других: репутация, дело жизни, образ в глазах общества.";
    return `Вопрос разбора: «${ctx.slotLabel}»
Позиция в карте: ${ctx.angle === "asc" ? "асцендент" : "середина неба"} ${signName(ctx.sign)}.
${what}

Ответь именно на этот вопрос.`;
  }

  const info = ASPECTS[ctx.aspect];
  const tone =
    info.tone === "hard"
      ? "Это напряжённый аспект: две части человека тянут в разные стороны. Покажи механику конфликта и что он даёт, если его не подавлять."
      : info.tone === "soft"
        ? "Это гармоничный аспект: части поддерживают друг друга. Не хвали — покажи, где лёгкость превращается в то, что человек не развивает, потому что и так получается."
        : "Это соединение: две части слиты и работают как одна. Покажи, что человеку трудно различить в себе.";
  return `Вопрос разбора: «${ctx.slotLabel}»
Аспект: ${info.name} между ${pointName(ctx.a)} и ${pointName(ctx.b)}.
${tone}

Ответь именно на этот вопрос: что эта связка делает с человеком.`;
}

export type BuiltNatalRequest = {
  version: number;
  temperature: number;
  system: string;
  user: string;
  maxTokens: number;
};

export function buildNatalRequest(ctx: NatalCtx): BuiltNatalRequest {
  return {
    version: NATAL_PROMPT_VERSION,
    temperature: 0.8,
    system: NATAL_SYSTEM_PROMPT,
    user: buildNatalPrompt(ctx),
    maxTokens: 900,
  };
}
