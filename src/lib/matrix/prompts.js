/**
 * Собирает готовый запрос к модели. Провайдер подставляется на бэкенде.
 * Тип задаётся полем kind. По умолчанию — ответ на вопрос в сфере.
 */
export function buildRequest(ctx) {
  const base = { version: PROMPT_VERSION, temperature: 0.8 };

  switch (ctx.kind) {
    case 'pair':
      return { ...base, system: PAIR_SYSTEM_PROMPT, user: buildPairPrompt(ctx), maxTokens: 700 };
    case 'point':
      return { ...base, system: SYSTEM_PROMPT, user: buildPointPrompt(ctx), maxTokens: 200 };
    case 'daily':
      return { ...base, system: DAILY_SYSTEM_PROMPT, user: buildDailyPrompt(ctx), maxTokens: 250 };
    case 'year':
      return { ...base, system: YEAR_SYSTEM_PROMPT, user: buildYearPrompt(ctx), maxTokens: 700 };
    case 'image':
      return { ...base, system: IMAGE_SYSTEM_PROMPT, user: buildImagePrompt(ctx), maxTokens: 200 };
    case 'mentor':
      return {
        ...base,
        system: `${MENTOR_SYSTEM_PROMPT}\n\n${buildMentorContext(ctx.matrix, ctx.person, ctx.plan)}`,
        messages: ctx.messages,   // вся история разговора
        maxTokens: 900,
        temperature: 0.9,
      };
    default:
      return { ...base, system: SYSTEM_PROMPT, user: buildUserPrompt(ctx), maxTokens: 700 };
  }
}
