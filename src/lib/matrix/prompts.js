/**
 * ПРОМПТЫ ГЕНЕРАЦИИ
 * =================
 * Тексты пишутся один раз и живут в базе вечно. Значит качество промпта —
 * самое важное решение в проекте: плохой промпт в первую неделю засорит базу
 * тысячей текстов, которые придётся перегенерировать.
 *
 * ВЕРСИОНИРОВАНИЕ: при изменении промпта поднимите PROMPT_VERSION.
 * Тексты, созданные старой версией, помечаются устаревшими и
 * перегенерируются, а не смешиваются с новыми.
 *
 * ГДЕ ЧТО ИСПОЛЬЗУЕТСЯ:
 *   'section' — ответ на вопрос внутри сферы (основной объём, 92 × 22)
 *   'pair'    — вопрос в парном разборе (совместимость, бизнес, мама и ребёнок)
 *   'point'   — короткая подсказка при клике на точку октаграммы
 *   'daily'   — аркан дня, генерируется ежедневно
 *   'year'    — личный год
 *   'image'   — короткий текст к AI-образу
 *   'mentor'  — чат с наставником, единственное место без кэша
 */

