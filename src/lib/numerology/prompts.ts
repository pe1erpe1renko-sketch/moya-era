const question = (id: NumerologyNumberId) => NUMEROLOGY_NUMBERS.find((n) => n.id === id)?.question ?? "";

export function buildNumPrompt(ctx: NumCtx): string {
  if (ctx.kind === "num_cell") {
    const label = squareLabels[ctx.digit - 1];
    if (ctx.count === 0) {
      return `Вопрос разбора: «${ctx.slotLabel}»
Ячейка квадрата Пифагора: цифра ${ctx.digit}, тема «${label}». В дате и рабочих числах она не встречается ни разу.

Ответь именно на этот вопрос: пустая ячейка не означает нехватки — качество не встроено по умолчанию и набирается опытом. Покажи, как это выглядит в жизни и что человек обычно делает вместо него.`;
    }
    const density =
      ctx.count === 1
        ? "Одна цифра — качество есть, но не выделяется: оно в норме и не определяет человека."
        : ctx.count === 2
          ? "Две цифры — качество заметное, на него можно опираться."
          : ctx.count === 3
            ? "Три цифры — качество сильное, оно уже видно окружающим."
            : ctx.count === 4
              ? "Четыре цифры — качество очень сильное, у него появляется обратная сторона."
              : "Пять и больше — качество избыточное. Пиши про то, как избыток мешает не меньше нехватки.";
    return `Вопрос разбора: «${ctx.slotLabel}»
Ячейка квадрата Пифагора: цифра ${ctx.digit}, тема «${label}», повторов ${ctx.count}. ${density}

Ответь именно на этот вопрос: как эта плотность проявляется в жизни. Не оценивай, много это или мало по сравнению с другими людьми.`;
  }

  const master = MASTER_NOTE[ctx.value] ? `\n${MASTER_NOTE[ctx.value]}` : "";

  if (ctx.kind === "num_brief") {
    return `Число: ${ctx.value}. Вопрос: ${question(ctx.number)}.
${ABOUT[ctx.number]}${master}

Напиши одну короткую справку об этом числе в этом вопросе: что оно означает и как выглядит в жизни.`;
  }

  return `Вопрос разбора: «${ctx.slotLabel}»
Число: ${ctx.value}.
${ABOUT[ctx.number]}${master}

Ответь именно на этот вопрос через это число.`;
}

export type BuiltNumRequest = {
  version: number;
  temperature: number;
  system: string;
  user: string;
  maxTokens: number;
};

export function buildNumRequest(ctx: NumCtx): BuiltNumRequest {
  const brief = ctx.kind === "num_brief";
  return {
    version: NUM_PROMPT_VERSION,
    temperature: 0.8,
    system: brief ? NUM_BRIEF_SYSTEM_PROMPT : NUM_SYSTEM_PROMPT,
    user: buildNumPrompt(ctx),
    maxTokens: brief ? 300 : 900,
  };
}

/** Контекст текста: ключ в базе плюс всё, что нужно промпту. */
export type NumSlotContext = NumCtx & { key: string; slotLabel: string };

/**
 * Что писать в этой позиции разбора.
 *
 * Значение числа спрашиваем у карты позиций, а не выводим здесь заново.
 * Пока чисел было четыре, значение подставлялось цепочкой условий; когда
 * пятым добавилось число судьбы, цепочка молча отдала ему значение
 * личного года — ключ говорил одно, а текст писался про другое. Теперь
 * источник значения один на всех, и разойтись им негде.
 */
export function numContextFor(slot: NumerologySlot, chart: NumerologyChart): NumSlotContext | null {
  const base = { key: slot.key, slotLabel: slot.label };

  if (slot.kind === "cell" && slot.cell) {
    return { ...base, kind: "num_cell", digit: slot.cell.digit, count: slot.cell.count };
  }

  // Идентификатор вида num_brief_path или num_path — из него берём число.
  const id = slot.id.replace(/^num_(brief_)?/, "") as NumerologyNumberId;
  const value = numberValue(chart, id);
  if (value === null) return null;

  if (slot.kind === "brief") return { ...base, kind: "num_brief", number: id, value };
  if (slot.kind === "number") return { ...base, kind: "num_number", number: id, value };
  return null;
}
