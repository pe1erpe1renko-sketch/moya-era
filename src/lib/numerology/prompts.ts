export type NumBriefCtx = { kind: "num_brief"; slotLabel: string; number: NumerologyNumberId; value: number };
export type NumNumberCtx = { kind: "num_number"; slotLabel: string; number: NumerologyNumberId; value: number };
export type NumCellCtx = { kind: "num_cell"; slotLabel: string; digit: number; count: number };

export type NumCtx = NumBriefCtx | NumNumberCtx | NumCellCtx;

const NUM_KINDS = new Set(["num_brief", "num_number", "num_cell"]);

export function isNumCtx(ctx: { kind?: string }): ctx is NumCtx {
  return typeof ctx.kind === "string" && NUM_KINDS.has(ctx.kind);
}

