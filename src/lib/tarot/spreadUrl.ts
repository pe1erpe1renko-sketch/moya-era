import { isShortCode } from "@/lib/shortCode";

/**
 * АДРЕС РАСКЛАДА — /rasklad/k7m2q9xw4tzp.
 *
 * Код случайный, страница закрыта от индексации. Это личный вопрос
 * человека, часто тяжёлый: ему не место в поиске, и по адресу не должно
 * восстанавливаться ничего.
 *
 * ДВЕНАДЦАТЬ ЗНАКОВ, а не десять, как у карточки образа. Карточкой
 * делятся нарочно, а расклад — переписка с самим собой: адресом,
 * попавшим не туда, человек рискует не картинкой, а вопросом, который
 * никому не рассказывал. При алфавите из 31 знака это 7,9·10¹⁷
 * вариантов — перебором не берётся.
 */

export const SPREAD_CODE_LENGTH = 12;

export function spreadPath(code: string): string {
  return `/rasklad/${code}`;
}

/** Годится ли строка как код расклада. Проверяется до похода в базу. */
export function isSpreadCode(value: string): boolean {
  return isShortCode(value, SPREAD_CODE_LENGTH);
}
