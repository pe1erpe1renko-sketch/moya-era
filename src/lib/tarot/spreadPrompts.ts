export type SpreadCardCtx = { arcanum: number; name: string; reversed: boolean; position: string };

export type SpreadCtx = {
  kind: "spread";
  /** название вида расклада */
  spread: string;
  /** вопрос человека своими словами */
  question: string;
  cards: SpreadCardCtx[];
};

export function buildSpreadPrompt(ctx: SpreadCtx): string {
  const cards = ctx.cards
    .map((c) => `${c.position}: ${c.arcanum}, ${c.name}${c.reversed ? ", перевёрнутая" : ""}`)
    .join("\n");

  return `Расклад: ${ctx.spread}.
Вопрос человека, его словами: «${ctx.question}»

Выпавшие карты:
${cards}

Прочитай этот расклад применительно к его вопросу.`;
}

export type BuiltSpreadRequest = {
  version: number;
  temperature: number;
  system: string;
  user: string;
  maxTokens: number;
};

export function buildSpreadRequest(ctx: SpreadCtx): BuiltSpreadRequest {
  return {
    version: SPREAD_PROMPT_VERSION,
    temperature: 0.85,
    system: SPREAD_SYSTEM_PROMPT,
    user: buildSpreadPrompt(ctx),
    // Большому раскладу нужно вдвое больше места: десять карт против трёх.
    maxTokens: ctx.cards.length >= 10 ? 2000 : 1200,
  };
}
