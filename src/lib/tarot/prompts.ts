/** Контекст текста: ключ в базе плюс всё, что нужно промпту. */
export type TaroSlotContext = TaroCtx & { key: string; slotLabel: string };

/** Что писать в этой позиции разбора. */
export function taroContextFor(slot: TarotSlot, card: DayCard): TaroSlotContext | null {
  const base = { key: slot.key, slotLabel: slot.label };
  if (slot.kind === "brief") return { ...base, kind: "taro_brief", arcanum: card.arcanum };
  if (slot.kind === "pair") {
    return { ...base, kind: "taro_pair", arcanum: card.arcanum, birthArcanum: card.birthArcanum };
  }
  const question = DAY_QUESTIONS[slot.id];
  if (!question) return null;
  return { ...base, kind: "taro_day", arcanum: card.arcanum, question };
}

export type BuiltTaroRequest = {
  version: number;
  temperature: number;
  system: string;
  user: string;
  maxTokens: number;
};

export function buildTaroRequest(ctx: TaroCtx): BuiltTaroRequest {
  const brief = ctx.kind === "taro_brief";
  return {
    version: TARO_PROMPT_VERSION,
    temperature: 0.8,
    system: brief ? TARO_BRIEF_SYSTEM_PROMPT : TARO_SYSTEM_PROMPT,
    user: buildTaroPrompt(ctx),
    maxTokens: brief ? 300 : 900,
  };
}
