export type TaroBriefCtx = { kind: "taro_brief"; slotLabel: string; arcanum: number };
export type TaroPairCtx = { kind: "taro_pair"; slotLabel: string; arcanum: number; birthArcanum: number };
export type TaroDayCtx = { kind: "taro_day"; slotLabel: string; arcanum: number; question: string };

export type TaroCtx = TaroBriefCtx | TaroPairCtx | TaroDayCtx;

const TARO_KINDS = new Set(["taro_brief", "taro_pair", "taro_day"]);

export function isTaroCtx(ctx: { kind?: string }): ctx is TaroCtx {
  return typeof ctx.kind === "string" && TARO_KINDS.has(ctx.kind);
}

const named = (n: number) => {
  const info = arcanumInfo(n);
  return `${n} — ${info.name} (${info.line.toLowerCase()})`;
};

export function buildTaroPrompt(ctx: TaroCtx): string {
  if (ctx.kind === "taro_brief") {
    return `Аркан дня: ${named(ctx.arcanum)}.

Напиши короткую справку: про что этот аркан, когда выпадает на день, и как такой день выглядит на деле.`;
  }

  if (ctx.kind === "taro_pair") {
    return `Вопрос разбора: «${ctx.slotLabel}»
Аркан дня: ${named(ctx.arcanum)}.
Аркан рождения этого человека: ${named(ctx.birthArcanum)}. Это его постоянное устройство, оно не меняется всю жизнь.

Ответь именно на этот вопрос: как сегодняшнее состояние ложится на постоянное устройство. Попадает ли аркан дня в то, что человеку и так даётся, или в то, чего у него мало, — и что из этого следует сегодня.${
      ctx.arcanum === ctx.birthArcanum
        ? "\n\nАрканы совпали. Это не «двойная сила»: скорее свой же способ действовать сегодня виден крупнее обычного, со всеми его последствиями."
        : ""
    }`;
  }

  return `Вопрос разбора: «${ctx.slotLabel}»
Аркан дня: ${named(ctx.arcanum)}.

${ctx.question}`;
}

