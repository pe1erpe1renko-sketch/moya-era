/**
 * АДРЕСА ИЛЛЮСТРАЦИЙ АРКАНОВ.
 *
 * Файлы лежат в `public/arcana/`, по номеру аркана: 01.jpeg … 22.jpeg.
 * Рядом два уменьшенных набора, `sm` и `md`, — их готовит
 * `scripts/build-arcana.py`. Оригинал отдаётся только там, где картинка
 * действительно большая: он весит триста килобайт, а на странице разбора
 * иллюстраций бывает до двадцати пяти сразу.
 *
 * ПОЧЕМУ ЭТОТ ФАЙЛ, А НЕ `matrix/contentPositions.js`. Там лежит такая же
 * функция, но с расширением `.png`, которого у присланных файлов нет.
 * Матричные файлы редактировать нельзя — методика закрыта, — поэтому
 * адреса картинок переехали сюда целиком, а тот экспорт больше никто не
 * зовёт.
 */

/** Размер иллюстрации: под размер на экране, а не «на всякий случай». */
export type ArcanaSize = "sm" | "md" | "lg" | "full";

/**
 * Ширина файла в пикселях — вдвое против размера на экране, ради плотных
 * экранов. Ступеней три, а не две: с двумя шапка разбора (рамка в 132
 * точки) тянула файл на 560 пикселей и одна весила больше, чем все
 * остальные картинки страницы вместе.
 */
export const ARCANA_WIDTH: Record<ArcanaSize, number> = { sm: 240, md: 320, lg: 560, full: 896 };

/**
 * Пропорции картинок: примерно три к четырём.
 *
 * У присланных файлов они чуть разные, от 0,736 до 0,750, — обрезать
 * чужую работу ради круглого числа незачем. Рамку задаёт вёрстка, а
 * картинка вписывается в неё по `object-cover`. Это же число резервирует
 * место до загрузки, чтобы страница не дёргалась.
 */
export const ARCANA_RATIO = 3 / 4;

export function arcanaImage(arcana: number, size: ArcanaSize = "sm"): string {
  const file = `${String(arcana).padStart(2, "0")}.jpeg`;
  return size === "full" ? `/arcana/${file}` : `/arcana/${size}/${file}`;
}
